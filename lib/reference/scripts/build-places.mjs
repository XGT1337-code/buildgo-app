// Builds src/data/places.ts from OpenStreetMap extracts in data-src/ (see README in this package).
//   places.json    — every place=city|town|village|hamlet node in Azerbaijan (out body)
//   districts.json — for each admin_level=6 area: the area, then the ids of the places inside it
// Data © OpenStreetMap contributors, ODbL 1.0.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = (f) => JSON.parse(readFileSync(path.join(here, "..", "data-src", f), "utf8"));

const clean = (s) => (s ?? "").replace(/\s+(rayonu|район|District|district)$/u, "").trim();
const districts = [];
const districtOf = new Map();
let cur = -1;
for (const e of src("districts.json").elements) {
  if (e.type === "area") {
    const t = e.tags;
    districts.push([clean(t["name:az"] || t.name), clean(t["name:ru"]), clean(t["name:en"] || t["int_name"])]);
    cur = districts.length - 1;
  } else if (cur >= 0 && !districtOf.has(e.id)) districtOf.set(e.id, cur);
}

const KIND = { city: 0, town: 1, village: 2, hamlet: 3 };
const seen = new Set();
const places = [];
for (const e of src("places.json").elements) {
  const t = e.tags;
  const az = (t["name:az"] || t.name || "").trim();
  if (!az || !(t.place in KIND)) continue;
  const d = districtOf.get(e.id) ?? -1;
  const key = `${az}|${d}`;
  if (seen.has(key)) continue;
  seen.add(key);
  places.push([az, (t["name:ru"] || "").trim(), (t["name:en"] || t["int_name"] || "").trim(), KIND[t.place], d,
    Math.round(e.lat * 1e4) / 1e4, Math.round(e.lon * 1e4) / 1e4]);
}
places.sort((a, b) => a[3] - b[3] || a[0].localeCompare(b[0], "az"));

mkdirSync(path.join(here, "..", "src", "data"), { recursive: true });
writeFileSync(path.join(here, "..", "src", "data", "places.ts"),
  `// Generated by scripts/build-places.mjs from OpenStreetMap. Data © OpenStreetMap contributors, ODbL 1.0.\n` +
  `// District: [az, ru, en]. Place: [az, ru, en, kind (0 city, 1 town, 2 village, 3 hamlet), district index or -1, lat, lon].\n` +
  `export const DISTRICTS: [string, string, string][] = ${JSON.stringify(districts)};\n` +
  `export const PLACES: [string, string, string, number, number, number, number][] = ${JSON.stringify(places)};\n`);
console.log(`districts ${districts.length}, places ${places.length}, without district ${places.filter((p) => p[4] < 0).length}`);
